export const textWidth = (s: string, scale = 1) =>
  s.length === 0 ? 0 : (s.length * 6 - 1) * scale;

export const text = (
  p: Pix,
  s: string,
  x: number,
  y: number,
  c: string,
  scale = 1,
  shadow?: string,
) => {
  if (shadow) text(p, s, x + scale, y + scale, shadow, scale);
  [...s.toUpperCase()].forEach((ch, k) => {
    const g = G[ch] ?? G["?"];
    for (let j = 0; j < 7; j++)
      for (let i = 0; i < 5; i++)
        if (g[j][i] === "1")
          p.rect(x + (k * 6 + i) * scale, y + j * scale, scale, scale, c);
  });
};

// Draw text centred on cx, optionally revealing only the first n characters.
export const textC = (
  p: Pix,
  s: string,
  cx: number,
  y: number,
  c: string,
  scale = 1,
  shadow?: string,
  n = s.length,
) => {
  const x = Math.round(cx - textWidth(s, scale) / 2);
  text(p, s.slice(0, n), x, y, c, scale, shadow);
};
